/**
 * 接入提示词（2026-10-30）
 *
 * 为什么有这东西：
 *   评委把站点接进 WorkBuddy 时，只拿到一段 mcp.json 是不够的 —— 对话方不知道
 *   "这个平台能干什么、有哪些红线、用户话说不全该怎么办、源码拉起来了服务怎么起"。
 *   所以这里生成一段**可以直接整段粘贴给对话方**的提示词，把 MCP 配置、能力清单、
 *   站点注意事项、本地源码启动方式、**信息不全时必须反问**这几件事一次说清。
 *
 * 用法：
 *   buildAgentPrompt({ origin, mcpUrl, tokenPlaceholder })
 *
 * ⛔ 页面里永远只出现占位符 <DEMO_TOKEN>；真值由服务端在运行时注入，不写进这段文本。
 */

/** 15 个工具的一句话能力（与 docs/MCP-TOOLS.md、TOOLS_BY_MODULE 对齐） */
export const CAPABILITIES = [
  "代取：task_publish 发布代取 / match_find_for_task 找顺路的跑腿同学（只推 60 分以上并给理由）/ runner_register 登记跑腿能力 / task_list_open 看开放单子 / task_parse_screenshot 从取件截图里抽楼栋与时间（不抽姓名手机号）",
  "搭子：buddy_publish 发一条搭子需求（匿名）/ buddy_search 按描述找搭子 / buddy_consent 双选表决（双方都同意才互相可见联系方式）",
  "导览：map_list_nodes 列校园地点（可分类）/ map_get_node 看某个地点的详情与是否有 360° 实景",
  "日程：schedule_import 导入课表（可直接贴文本；夹带的老师/学号等身份字段会被丢弃并记审计）/ schedule_add 加一条 / schedule_query 查 / schedule_remove 删",
  "打开界面：app_open_view 生成可点的深链，把某个界面或某处 360° 实景直接替用户打开",
];

export function buildAgentPrompt({ origin = "", mcpUrl = "", tokenPlaceholder = "<DEMO_TOKEN>" } = {}) {
  const site = origin || "（站点地址）";
  const endpoint = mcpUrl || `${site}/mcp`;
  return [
    "# 北民大小助手 · 校园服务 Agent 接入说明（整段粘给对话方即可）",
    "",
    "## 一、我是什么",
    "北民大小助手是一个校园服务 Agent（银移杯赛道 17）：把「代取快递撮合、搭子匹配、迎新导览与 360° 实景、日程提醒」四件事做成一个平台，",
    `并把全部能力通过远程 MCP（Streamable HTTP）开放出来：${endpoint}`,
    "站点点开后是给人看的；接上 MCP 之后，你可以直接替用户把事办完，不用他点任何按钮。",
    "",
    "## 二、怎么接",
    "1) 把下面这段 JSON 合并进你的 mcp.json（已有 mcpServers 时只添一个键）：",
    "```json",
    "{",
    '  "mcpServers": {',
    '    "beimingda": {',
    `      "url": "${endpoint}",`,
    '      "headers": { "Authorization": "Bearer ' + tokenPlaceholder + '" }',
    "    }",
    "  }",
    "}",
    "```",
    "2) 重启并信任一次；连接器列表里能看到 15 个工具就算接好了。",
    `3) 自检：让对话方列出工具（tools/list）应看到 15 个；或直接请求 ${site}/api/health 应返回 ok:true。`,
    "⚠️ 写操作（发布、接单、表决、导入课表）需要上面那个 Bearer 令牌；只读操作也需要它（服务端统一鉴权）。",
    "",
    "## 三、接上之后能做什么（15 个工具，按模块）",
    ...CAPABILITIES.map((c) => `- ${c}`),
    "",
    "## 四、这个站点的注意事项（重要，别踩）",
    "- 不收集任何身份信息：姓名、学号、手机号、身份证、学生证照片、校园网账号口令——服务端没有存这些的字段。",
    "  → 用户如果发来含这些内容的材料，**不要原样转发**，也不要塞进任何参数；服务端的脱敏层会丢弃并只把字段名记进审计。",
    "- 不接、不登录、不抓取学校任何内部系统；数据全部来自平台自己的库（演示库是虚构数据）。",
    "- 课表只有一个入口：对话。**不要在页面上找上传课表的按钮**（没有），直接把用户贴的课表文本交给 schedule_import。",
    "- 360° 实景是实拍素材拼的：没拍过的点位会如实说「暂无实景」，**不要编造位置或拿别的图顶替**。",
    "- 写接口限频（默认 60 次/分钟，读接口 240 次/分钟）：批量操作要收敛，遇到限频请稍后重试，不要死循环重试。",
    "- 演示数据带 demo 标记；演示前可用 `/api/demo/seed?reset=1` 重置（需令牌）。",
    "",
    "## 五、如果拿到的是源码，服务起不来怎么办（评委常见场景）",
    "按这个顺序自查，**不要猜**：",
    "1) 环境：需要 Node 20 或更高（`node -v`）。依赖装好：`npm install`。",
    "2) 数据：`npm run seed`（会建库 `data/beimingda.db` 并灌演示数据；schema 是幂等的，可重复执行）。",
    "3) 启动：默认端口 3000，本机如被占用请显式指定：`PORT=3080 npm start`（Windows PowerShell 用 `$env:PORT=3080; npm start`）。",
    "4) 验证：`GET /api/health` 返回 `{ok:true}`；`GET /api/map/nodes` 能拿到点位。",
    "5) 令牌：写接口需要 `DEMO_TOKEN`。仓库根目录的 `.env` 里配置（`.env.example` 有占位）；没有就自己设一个，然后 MCP 的 Authorization 用同一个值。",
    "6) 接 MCP：把上面的 mcp.json 里的 url 换成本机地址 `http(s)://127.0.0.1:<端口>/mcp`，重启对话方即可。",
    "7) 还不行：读 `README.md` 与 `docs/`（架构、库表、MCP 工具清单都在里面）；也可以直接读源码 `src/server.js`（入口）、`src/api/`（HTTP 接口）、`src/mcp/`（工具注册）。",
    "",
    "## 六、用户话说不全时必须反问（这条最重要）",
    "**信息不完整就反问、补齐再动手**，⛔ 不要自己假设默认值，也不要编造站点上不存在的地点。",
    "- 代取：楼栋（从哪取 / 送到哪）、取件点（快递驿站/南门…）、截止时间、报酬区间。缺一个就问一个。",
    "- 搭子：做什么、大概什么时候、在哪、期望对方什么样。",
    "- 课表：星期几、第几节、课程名；教室与周次可选。",
    "- 地点类请求：先 `map_list_nodes` 核对有没有这个地点；没有就如实告诉用户「站点上没有这个地点」，并给出最接近的选项让他确认。",
    "- 涉及身份信息的请求（例如「把我的学号写进备注」）：明确拒绝并说明原因，不要绕道写入。",
    "- 用户说的条件自相矛盾（例如报酬上限低于下限、截止时间已过）：指出来并请他确认，不要硬提交（服务端也会拒绝）。",
    "",
    "## 七、回复风格",
    "- 简洁、给结果；需要用户点开某个界面时，用 app_open_view 生成深链直接给出可点地址。",
    "- 涉及分数/理由（撮合、搭子匹配）时，把服务端给的理由原样带上，别改写数字。",
  ].join("\n");
}

export default { buildAgentPrompt, CAPABILITIES };
